// 是为流式回放裁剪的短文档（代码围栏 + 表格 + 悬空标记的关键帧在其前缀中）。

const CODE_LINES = [
  'export interface SessionConfig {',
  '  id: string;',
  '  retries: number;',
  '  verbose: boolean;',
  '}',
  '',
  'const DEFAULT_RETRIES = 3;',
  'const MAX_TIMEOUT_MS = 30_000;',
  '',
  'export function buildConfig(id: string): SessionConfig {',
  '  return { id, retries: DEFAULT_RETRIES, verbose: false };',
  '}',
  '',
  'export async function runSession(id: string): Promise<void> {',
  '  const config = buildConfig(id);',
  '  let attempt = 0;',
  '  while (attempt <= config.retries) {',
  '    try {',
  '      await connect(config);',
  '      log(`session ${id} connected on attempt ${attempt}`);',
  '      return;',
  '    } catch (error) {',
  '      attempt += 1;',
  '      if (attempt > config.retries) throw error;',
  '      await delay(250 * attempt);',
  '    }',
  '  }',
  '}',
  '',
  'function delay(ms: number): Promise<void> {',
  '  return new Promise((resolve) => setTimeout(resolve, ms));',
  '}',
  '',
  'async function connect(config: SessionConfig): Promise<void> {',
  '  const endpoint = `wss://relay.example.com/v1/sessions/${config.id}`;',
  '  const socket = await openSocket(endpoint, { timeout: MAX_TIMEOUT_MS });',
  '  socket.onmessage = (event) => route(event);',
  '  socket.onclose = () => scheduleReconnect(config);',
  '}',
  '',
  'function scheduleReconnect(config: SessionConfig): void {',
  '  const backoff = Math.min(1000 * Math.pow(2, pendingCount(config.id)), 30_000);',
  '  setTimeout(() => void runSession(config.id), backoff);',
  '}',
  '',
  'interface RelayEvent {',
  '  kind: string;',
  '  payload: unknown;',
  '}',
  '',
  'function route(event: RelayEvent): void {',
  '  switch (event.kind) {',
  "    case 'message':",
  '      appendMessage(event.payload);',
  '      break;',
  "    case 'terminal':",
  '      finishRun(event.payload);',
  '      break;',
  '    default:',
  '      ignore(event);',
  '  }',
  '}',
];

