/** 流式回放样本：前缀帧依次经过悬空粗体 → 围栏未闭合 → 表格未成形 → 终态 */
export const STREAM_DOC = [
  '前言：本轮 **重点** 在流式口径。',
  '',
  '```ts',
  'const answer = 42;',
  'console.log(answer);',
  '```',
  '',
  '| 列甲 | 列乙 |',
  '| --- | --- |',
  '| 甲一 | 乙一 |',
  '| 甲二 | 乙二 |',
  '',
  '结尾段落，表格在此前已经成型。',
].join('\n');

/** 在 STREAM_DOC 中按锚点切出的关键帧（前缀字符串，含锚点文本） */
export function streamFrameAt(anchor: string): string {
  const index = STREAM_DOC.indexOf(anchor);
  if (index < 0) throw new Error(`锚点不存在：${anchor}`);
  return STREAM_DOC.slice(0, index + anchor.length);
}
