function spinnerStyle(style: SvgIconProps['style']): SvgIconProps['style'] {
  if (typeof style === 'string') {
    return `animation: spin 1s linear infinite; ${style}`;
  }
  if (style && typeof style === 'object') {
    return { animation: 'spin 1s linear infinite', ...(style as JSX.CSSProperties) };
  }
  return 'animation: spin 1s linear infinite';
}

