/**
 * 导出经过 OneWorks Avatar 引擎几何规范强制校验的 3D 几何部件
 * 保证 scaleX, scaleY, scaleZ 在 [0.08, 1.5] 范围内，topScale 在 [0.4, 1.2] 等
 */
const FACE_ANCHOR_MAP: Record<CustomCreationId, string> = {
  'grand-piano': 'piano-black-keys',
  'retro-walkman': 'walkman-spool-l',
  'milk-bottle': 'choc-chip-1',
  'kitchen-mixer': 'mixer-base',
  'sandcastle': 'castle-gate',
  'acoustic-guitar': 'guitar-soundhole',
  'blue-mosque': 'mosque-arch-gate',
  'tropical-flower': 'flower-core-shadow',
  'flamingo': 'flamingo-beak-tip',
  'jazz-clarinet': 'clarinet-mouthpiece',
  'rock-drums': 'drum-pedal',
  'emerald-crab': 'crab-eye-l',
};

export function createCustomCreationParts(
  id: CustomCreationId,
  palette: SunlitPaletteConfig
): AvatarEntityPart[] {
  const raw = getRawCustomCreationParts(id, palette);
  const targetFaceId = FACE_ANCHOR_MAP[id] || raw[0].id;

  return raw.map(part => ({
    ...part,
    // 严格规范：仅指定的深色/黑色暗影部件承载 face 标记，投影在此处完全无可见色差
    face: part.id === targetFaceId,
    scaleX: Math.max(0.08, Math.min(1.5, Math.round(part.scaleX * 100) / 100)),
    scaleY: Math.max(0.08, Math.min(1.5, Math.round(part.scaleY * 100) / 100)),
    scaleZ:
      part.scaleZ !== undefined
        ? Math.max(0.08, Math.min(1.5, Math.round(part.scaleZ * 100) / 100))
        : undefined,
    roundness:
      part.roundness !== undefined
        ? Math.max(0, Math.min(100, Math.round(part.roundness)))
        : undefined,
    bottomTaper:
      part.bottomTaper !== undefined
        ? Math.max(0, Math.min(100, Math.round(part.bottomTaper)))
        : undefined,
    topScale:
      part.topScale !== undefined
        ? Math.max(0.4, Math.min(1.2, Math.round(part.topScale * 100) / 100))
        : undefined,
    occlusionAmount:
      part.occlusionAmount !== undefined
        ? Math.max(0, Math.min(100, Math.round(part.occlusionAmount)))
        : undefined,
  }));
}

