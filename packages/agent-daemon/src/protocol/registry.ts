import type { DaemonInboundMessage, DaemonOutboundMessage } from "../types.js";
import type { DaemonProtocolCapability } from "./schema-groups.js";

export type DaemonProtocolCapabilityState =
  | "implemented"
  | "experimental"
  | "unsupported"
  | "degraded"
  | "backend-not-wired";

export interface DaemonProtocolMessageRegistration {
  capability: DaemonProtocolCapability;
  state: DaemonProtocolCapabilityState;
}

type ExactTypeList<TList extends readonly string[], TUnion extends string> =
  Exclude<TUnion, TList[number]> extends never
    ? Exclude<TList[number], TUnion> extends never
      ? TList
      : never
    : never;

function defineInboundMessageTypes<const T extends readonly DaemonInboundMessage["type"][]>(
  types: ExactTypeList<T, DaemonInboundMessage["type"]>
): T {
  return types;
}

function defineOutboundMessageTypes<const T extends readonly DaemonOutboundMessage["type"][]>(
  types: ExactTypeList<T, DaemonOutboundMessage["type"]>
): T {
  return types;
}

